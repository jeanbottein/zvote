#!/usr/bin/env node
/**
 * Builds what super-vote knows of geography, from two public-domain sources,
 * and keeps it out of politics: no country, no border, only land, sea and the
 * cities that name time zones.
 *
 * - servers/java/.../statistics/TimeZones.java: every IANA time zone name a
 *   browser may report, old ones included (Asia/Calcutta), and the zone it
 *   stands for (Asia/Kolkata), from tzdata's zone.tab and backward links.
 * - clients/web/src/statistics/worldMap.json: the land, in the Equal Earth
 *   projection, from Natural Earth; and for each zone, its city, its region
 *   (the first part of its name: Europe, Pacific...) and where the city is on
 *   that map, from the coordinates zone.tab gives it.
 *
 * Usage: node tools/geography/build.mjs   (Node 20+, curl and tar, network)
 * It downloads its sources into a temporary folder, and runs mapshaper
 * through npx. Run it again when tzdata changes; review the diff.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const JAVA_OUT = join(ROOT, 'servers/java/src/main/java/org/supervote/server/statistics/TimeZones.java');
const MAP_OUT = join(ROOT, 'clients/web/src/statistics/worldMap.json');

const LAND = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_50m_land.geojson';
const TZDATA = 'https://data.iana.org/time-zones/tzdata-latest.tar.gz';
const MAPSHAPER = 'mapshaper@0.7.83';

/** Antarctica is left off the map, which it would make a third taller: its stations are listed only. */
const SOUTHMOST = -60;

const work = mkdtempSync(join(tmpdir(), 'super-vote-geography-'));
const file = (name) => join(work, name);
const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));

function download(url, name) {
  execFileSync('curl', ['-sSfL', '-o', file(name), url], { stdio: 'inherit' });
  return file(name);
}

// --- tzdata: the zones, their cities, and the old names ------------------------

/** ISO 6709, as zone.tab writes it: ±DDMM[SS]±DDDMM[SS], as [longitude, latitude]. */
function coordinates(text) {
  const [, latitude, longitude] = text.match(/^([+-]\d+)([+-]\d+)$/);
  const degrees = (part, width) => {
    const sign = part[0] === '-' ? -1 : 1;
    const digits = part.slice(1);
    const whole = Number(digits.slice(0, width));
    const minutes = Number(digits.slice(width, width + 2));
    const seconds = Number(digits.slice(width + 2) || 0);
    return sign * (whole + minutes / 60 + seconds / 3600);
  };
  return [degrees(longitude, 3), degrees(latitude, 2)];
}

function timeZones() {
  execFileSync('tar', ['-xzf', download(TZDATA, 'tzdata.tar.gz'), '-C', work, 'zone.tab', 'backward', 'version']);
  const version = readFileSync(file('version'), 'utf8').trim();
  const zones = [];
  for (const line of readFileSync(file('zone.tab'), 'utf8').split('\n')) {
    if (line && !line.startsWith('#')) {
      const [, place, zone] = line.split('\t');
      zones.push({ zone, at: coordinates(place) });
    }
  }
  const canonical = new Map(zones.map(({ zone }) => [zone, zone]));
  // Old names browsers may still report (Asia/Calcutta, US/Eastern). Names
  // without a region (CET, EST5EDT, PRC) name no place.
  for (const line of readFileSync(file('backward'), 'utf8').split('\n')) {
    const [kind, target, link] = line.split('#')[0].trim().split(/\s+/);
    if (kind === 'Link' && link.includes('/') && !link.startsWith('Etc/')
        && canonical.has(target) && !canonical.has(link)) {
      canonical.set(link, target);
    }
  }
  return { version, zones, canonical: [...canonical].sort(([a], [b]) => a.localeCompare(b)) };
}

function javaSource({ version, canonical }) {
  const entries = canonical.map(([name, zone]) => `        Map.entry("${name}", "${zone}")`).join(',\n');
  return `package org.supervote.server.statistics;

import java.util.Map;

/**
 * Every IANA time zone name a browser may report, and the zone of tzdata's
 * zone.tab it stands for: Asia/Calcutta is Asia/Kolkata. Generated by
 * tools/geography/build.mjs from tzdata ${version}: do not edit, run it again.
 */
final class TimeZones {

    static final Map<String, String> CANONICAL = Map.ofEntries(
${entries});

    private TimeZones() {
    }
}
`;
}

// --- Natural Earth: the land, and where the cities are ------------------------

function project(zones) {
  const land = readJson(download(LAND, 'land-source.json'));
  land.features = land.features.filter((feature) => rings(feature.geometry).flat().some(([, y]) => y > SOUTHMOST));
  writeFileSync(file('land.json'), JSON.stringify(land));
  writeFileSync(file('cities.json'), JSON.stringify({
    type: 'FeatureCollection',
    features: zones.map(({ zone, at }) => ({
      type: 'Feature', properties: { zone }, geometry: { type: 'Point', coordinates: at },
    })),
  }));
  mkdirSync(file('projected'));
  execFileSync('npx', ['--yes', MAPSHAPER,
    '-i', file('land.json'), file('cities.json'), 'combine-files',
    '-dissolve', 'target=land',
    '-proj', '+proj=eqearth', 'target=*',
    '-simplify', 'visvalingam', 'interval=8000', 'keep-shapes',
    '-filter-slivers', 'min-area=4e6', 'target=land',
    '-o', 'format=geojson', `${file('projected')}/`, 'target=*',
  ], { stdio: 'inherit' });
  // Land without attributes comes back as bare geometries.
  const projected = readJson(file('projected/land.json'));
  const shapes = projected.features ?? projected.geometries.map((geometry) => ({ geometry }));
  return [{ features: shapes }, readJson(file('projected/cities.json'))];
}

function rings(geometry) {
  if (!geometry) return [];
  return geometry.type === 'Polygon' ? geometry.coordinates : geometry.coordinates.flat();
}

function svgMap(land, cities, zones) {
  // Projected metres to a 1000-wide picture, y downwards, framed on the land.
  const points = land.features.flatMap((feature) => rings(feature.geometry).flat());
  const minX = Math.min(...points.map(([x]) => x));
  const maxX = Math.max(...points.map(([x]) => x));
  const minY = Math.min(...points.map(([, y]) => y));
  const maxY = Math.max(...points.map(([, y]) => y));
  const scale = 1000 / (maxX - minX);
  const at = ([x, y]) => [Math.round((x - minX) * scale * 10), Math.round((maxY - y) * scale * 10)];
  const path = land.features.flatMap((feature) => rings(feature.geometry)).map((ring) => {
    let d = '';
    let last = null;
    for (const point of ring.map(at)) {
      if (last === null) {
        d += `M${point[0] / 10} ${point[1] / 10}`;
      } else if (point[0] !== last[0] || point[1] !== last[1]) {
        d += `l${(point[0] - last[0]) / 10} ${(point[1] - last[1]) / 10}`;
      }
      last = point;
    }
    return d + 'z';
  }).join('');
  const projected = new Map(cities.features.map((feature) => [feature.properties.zone, feature.geometry.coordinates]));
  const places = {};
  for (const { zone, at: [, latitude] } of [...zones].sort((a, b) => a.zone.localeCompare(b.zone))) {
    const parts = zone.split('/');
    const [x, y] = at(projected.get(zone));
    places[zone] = {
      city: parts.at(-1).replaceAll('_', ' '),
      region: parts[0],
      // Antarctica's stations are listed, not drawn.
      ...(latitude > SOUTHMOST ? { x: x / 10, y: y / 10 } : {}),
    };
  }
  return { width: 1000, height: Math.ceil((maxY - minY) * scale), land: path, places };
}

const tz = timeZones();
writeFileSync(JAVA_OUT, javaSource(tz));
const [land, cities] = project(tz.zones);
const map = svgMap(land, cities, tz.zones);
writeFileSync(MAP_OUT, JSON.stringify(map) + '\n');
console.log(`Wrote ${JAVA_OUT} and ${MAP_OUT} (${Object.keys(map.places).length} places, tzdata ${tz.version}).`);
